<h2>Why three pages is enough for many Michigan businesses</h2>
<p><a href="<?php echo webstar_h(webstar_url('packages/simple-website/')); ?>">Simple Website</a> is three pages on purpose: one job per page — trust, services, contact. Guides, trades, and shops across Metro Detroit convert on that structure when intake is clear. This is the outline I ask you to approve before design starts.</p>

<h2>Home — trust in ten seconds</h2>
<p>Headline = outcome, not fluff (“Furnace repair in Warren and Sterling Heights,” not “Welcome”). Above the fold on mobile: tap-to-call, honest hours, one real photo. One short proof line you can back up (years in business, license, family-owned — not fake star counts). Link clearly to Services and Contact.</p>
<p>Below the fold: scannable top services, optional three-step “how it works,” service cities only where true. Skip novel-length history; save story for a short blurb on Services.</p>

<h2>Services — specificity sells</h2>
<p>Plain headings (“Water heater replacement,” not internal codes). Two to four sentences each: what is included, timing, whether you quote on site. Bullets for what you <em>do not</em> do — that filters bad leads. On three pages, skip blogs and full staff CVs; best Instagram shots can stay on Instagram, but mirror winners on-site for Google.</p>

<h2>Contact — remove friction</h2>
<p>Tap-to-call, email you monitor, short form (name, phone, message, optional service). State response time and service area again. Hours must match <a href="<?php echo webstar_h(webstar_url('resources/google-business-profile-checklist-metro-detroit/')); ?>">Google Business Profile</a>. One booking button is fine when scope allows; heavier booking often means <a href="<?php echo webstar_h(webstar_url('packages/business-website/')); ?>">Business Website</a> tier.</p>

<h2>Bring to intake</h2>
<ul>
<li>Logo (PNG or SVG)</li>
<li>Six to twelve real job or product photos</li>
<li>Service list with explicit “we do not…” lines</li>
<li>Cities served and who answers the phone</li>
<li>Domain name (or desired name)</li>
</ul>

