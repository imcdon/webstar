<h2>Ownership is the part people misunderstand</h2>
<p>Outright means you own files when we launch — staging review happens before DNS goes live. WaaS ownership starts after month six when you get a full export, even if you keep paying $150 for convenience. Before six months, exiting early means settling the remaining minimum — that covers the build labor baked into the monthly fee.</p>
<p>If we part ways, you still have your domain and Google properties. Only hosting and who updates the HTML changes.</p>

<h2>When I steer you toward outright</h2>
<ul>
<li>You have cash from a busy season, a loan, or a franchise checklist with a deadline.</li>
<li>Your menu or services rarely change — the Care Plan’s 120 minutes would go unused.</li>
<li>You already know you only need Simple scope: calls, not booking.</li>
</ul>
<p>Many one-truck trades and established shops treat the site like signage: pay once, call when something breaks.</p>

<h2>When I steer you toward WaaS</h2>
<ul>
<li>Opening in 2026 and every dollar is earmarked for equipment or inventory.</li>
<li>You expect weekly hour, menu, or promo tweaks and want edits bundled.</li>
<li>Business Website scope fits your needs but $900–$1,800 upfront would drain the buffer.</li>
</ul>
<p>We fix scope in writing at signing — pages, booking, brand pieces — then spread delivery while the site is live.</p>

