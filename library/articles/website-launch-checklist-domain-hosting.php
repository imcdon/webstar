<h2>Launch week is a checklist sport</h2>
<p>Design approval feels like the finish line, but DNS, forms, and Google tools separate a pretty staging site from a business asset. I run through this list on every Webstar launch — from $350 Simple sites to $2,500+ growth builds — so Michigan owners are not debugging email at midnight before a snowstorm rush.</p>

<h2>Before go-live: domain and registrar</h2>
<p>Confirm the domain is registered in your name at a registrar you control — not mine. Unlock domain if transferring. Decide www vs non-www; we pick one canonical and redirect the other. Lower TTL a day before cutover if migrating hosts.</p>

<h2>Hosting and SSL</h2>
<p>Point A record or nameservers to agreed hosting — Webstar Care, your cPanel host, or WaaS included hosting. SSL certificate should auto-issue via Let’s Encrypt or host tooling. Visit https:// version and confirm padlock without mixed-content warnings from old http images.</p>

<h2>DNS email records</h2>
<p>If you use Google Workspace or Microsoft 365, MX records must stay correct while web records change. I verify web does not break mail — a common DIY mistake when adding A records blindly.</p>

<h2>Site functionality tests</h2>
<ul>
<li>Submit contact form from mobile data; confirm email delivery and autoresponder if any</li>
<li>Tap every phone link on iOS and Android</li>
<li>Test booking button if on Business Website tier</li>
<li>Check 404 page and favicon</li>
<li>Run quick accessibility pass — focus states, alt text on hero</li>
</ul>

<h2>Analytics and Search Console</h2>
<p>GA4 property under your Google login with call and form events firing. Search Console verified for domain or URL prefix. Submit sitemap. Exclude staging domains from indexing if they still exist.</p>

<h2>Google Business Profile sync</h2>
<p>Update website field to production URL. Confirm categories, hours, and service areas match the live site footer. Upload two fresh photos launch week for freshness signal.</p>

<h2>Performance and backups</h2>
<p>Compress large images if any slipped through. Enable host backups or Care Plan backups before announcing. Note where backup restore is requested if malware ever hits shared hosting.</p>

<h2>Legal and trust pages</h2>
<p>Link privacy policy if you collect form data — Webstar sites include standard footer links to site-wide privacy. Terms if you take online deposits. Accessibility statement if you want public commitment — we host one at webstarbusinessservices.com you can mirror philosophically on yours.</p>

<h2>Post-launch communications</h2>
<p>Update Facebook, Instagram, and email signature with new URL. Tell staff what form notifications look like so leads are not ignored. Set calendar reminder for 30-day fix window end — report bugs before it closes.</p>

<h2>WaaS vs outright handoff differences</h2>
<p>WaaS clients stay on managed hosting with care included during the minimum term. Outright buyers get archive zip and credentials document. Both receive Google account checklist showing manager roles.</p>

<h2>When to call for help</h2>
<p>DNS not propagating after 24 hours, form spam flooding, or redirect loops — email me during the fix window. Launch is not the time to rename the business or swap domains; freeze scope for two weeks so Google stabilizes.</p>
<p>Print this checklist for your office manager. Done right, launch day is boring — and boring means phones ring for the right reasons across Metro Detroit.</p>
<h2>Registrar two-factor authentication</h2>
<p>Enable 2FA on Namecheap, Cloudflare, or wherever the domain lives before launch week. Losing registrar access during a DNS change is a nightmare I have seen stall Michigan shops for days.</p>

<h2>Staging vs production hygiene</h2>
<p>Password-protect staging or noindex it. Remove test form entries from databases. Delete placeholder lorem before Google crawls production. robots.txt on production should allow indexing unless you intentionally soft-launch.</p>

<h2>301 redirects from old URLs</h2>
<p>Changing from builder subpaths to clean slugs needs a redirect map. One wrong 404 on an old blog post can drop referral traffic. Keep a spreadsheet of old → new for six months.</p>

<h2>Form spam and deliverability</h2>
<p>Turn on basic spam filtering or honeypot fields. Confirm messages do not land in Gmail Promotions. Add hello@ to contacts on office phones.</p>

<h2>Monitoring first 72 hours</h2>
<p>Watch Search Console for crawl errors. Check Analytics realtime while you text five friends to click around. Listen for duplicate Analytics tags if old builder code lingered on DNS elsewhere.</p>

<h2>Team training checklist</h2>
<p>Who answers after-hours form leads? Who updates snow day hours? Write names on a laminated sheet. Webstar documents Google login locations — store paper copy in office safe.</p>

<h2>Long-term hosting costs</h2>
<p>Budget $120–$300 yearly for shared hosting or fold into Care Plans. WaaS includes hosting during subscription. Plan renewals before auto-expire catches you mid-July heat wave when AC calls spike.</p>
<h2>Email marketing and CRM hooks</h2>
<p>Mailchimp or Constant Contact verification often needs a TXT record — add it before blast day. CRM embeds should load after core content so phones still get click-to-call instantly on 3G in rural Washtenaw job sites.</p>

<h2>Security headers and backups test</h2>
<p>Confirm HTTPS redirects globally. Run a restore drill on hosting if available — knowing backup works beats assuming. Change default admin passwords on any CMS components.</p>

<h2>Launch communication template</h2>
<p>Draft a short email and social post before DNS switch: new URL, same phone, better mobile experience. Staff should know the site changed so they do not tell customers “use the old link.”</p>

<h2>Business Website-specific launch items</h2>
<p>Test booking integration with a real appointment you cancel. Verify brand kit PDFs download on iPhone. Print one proof flyer if physical promos launch same week as web.</p>

<h2>Custom growth launches at $2,500+</h2>
<p>Integration credentials rotate — document API keys in your password manager, not email threads. Load-test forms if you expect campaign traffic from radio or sponsorships at Michigan events.</p>

<h2>Post-launch SEO patience</h2>
<p>Search Console may take days to show impressions after DNS propagates. Avoid renaming URLs in week two unless legally required. If you migrate from a builder, keep old property view in Analytics thirty days to compare traffic sources while the new canonical settles. Map-pack clicks often lag a week behind site go-live — that is normal, not a sign the launch failed.</p>
