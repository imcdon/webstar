<h2>Who this checklist is for</h2>
<p>Metro Detroit service businesses and storefronts — Wayne, Oakland, Macomb — where customers search on Maps first. I configure profiles on every Webstar build; you complete Google’s verification steps. Pair this with a site whose footer NAP matches the profile.</p>

<h2>1. Claim the right listing</h2>
<p>Search your exact business name on Maps. Claim an unowned pin or merge duplicates from old addresses. Service-area and home-based businesses: follow Google’s address visibility rules — no fake suites. Use a company Google account you control long term.</p>

<h2>2. Categories</h2>
<p>One primary category that matches how you make money. Secondaries only for real add-ons. Salons split hair vs nails carefully. Changing categories shifts impressions — note Search Console baselines before big edits.</p>

<h2>3. Service area vs storefront</h2>
<p>Storefronts: public address and foot-traffic hours. Service-area: hide home address; list cities or ZIPs you truly serve. Website footer and contact page must use the same geography.</p>

<h2>4. Phone, site, booking</h2>
<p>Main line you answer — ideally <a href="<?php echo webstar_h(webstar_url('contact/')); ?>">the same number on your site</a>. Website URL = HTTPS canonical domain. Appointment links go to your booking page, not a surprise Facebook tab.</p>

<h2>5. Description and services</h2>
<p>Plain language: who, where, one real differentiator. Skip keyword paragraphs. Named services with “call for quote” are fine when that is how you price.</p>

<h2>6. Photos</h2>
<p>Real team, truck, and job photos monthly. Stock hard-hats hurt trust. Blur plates or faces when needed.</p>

<h2>7. Hours and attributes</h2>
<p>Regular hours plus holiday special hours before busy weekends. Attributes (women-owned, wheelchair access, etc.) only when true.</p>

<h2>8. Verification and reviews</h2>
<p>Finish postcard, phone, or email verification promptly. After delivery, ask happy customers — see <a href="<?php echo webstar_h(webstar_url('resources/first-10-google-reviews-small-business/')); ?>">first ten reviews</a>. Never buy or script reviews.</p>

<h2>9. Connect Google tools</h2>
<p>Analytics and Search Console under your login — included on Webstar packages. Confirm the profile website field after launch using the <a href="<?php echo webstar_h(webstar_url('resources/website-launch-checklist-domain-hosting/')); ?>">launch checklist</a>.</p>

