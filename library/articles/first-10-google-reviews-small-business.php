<h2>Reviews follow work, not guilt</h2>
<p>The first ten Google reviews feel steep when competitors show dozens. You do not need hundreds to be credible — you need a accurate profile, a site that matches it, and steady real feedback. Webstar packages handle the digital foundation; this is the habit only you can run.</p>

<h2>Before you ask</h2>
<p>Claim and verify Business Profile. Name, phone, and site match the footer. Real photos and honest service areas — see the <a href="<?php echo webstar_h(webstar_url('resources/google-business-profile-checklist-metro-detroit/')); ?>">GBP checklist</a>. Asking on a broken listing wastes goodwill.</p>

<h2>Who and when</h2>
<p>Ask customers who got a clear win — on time, fair price, problem solved. Skip fake accounts, paid packs, and keyword scripts you wrote for them. Time the ask at satisfaction: checkout, invoice email, or within a few hours of a finished job — not while something is still open.</p>

<h2>Make it easy</h2>
<p>Use Google’s review link from the profile dashboard. Laminated counter card, SMS template, email footer, QR at checkout. Staff line: “If we earned it, a Google review helps neighbors find us.” Never gate service on stars.</p>

<h2>Respond early</h2>
<p>Thank specific five-star reviews. On criticism, stay professional, invite offline fix, improve ops. Prospects read responses, not just averages.</p>

<h2>Website pairing</h2>
<p>Link to live Google reviews when you have volume — no fake widgets. Written testimonials on the site only with customer permission (Business tier has room; Simple can link out).</p>

<h2>Pace to ten</h2>
<p>One to two real reviews per week beats thirty in a weekend. Seasonal businesses can stack summer wins before winter slowdown.</p>

<h2>Do not</h2>
<ul>
<li>Buy review bundles</li>
<li>Swap reviews with unrelated businesses</li>
<li>Flood from one IP in an hour</li>
</ul>

<h2>After ten</h2>
<p>Build the ask into job closeout like locking the toolbox. Fresh profile photos monthly. Track calls and forms in Analytics — reviews lift conversion, not vanity alone.</p>

